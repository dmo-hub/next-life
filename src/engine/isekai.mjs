const isekaiClamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));
function isekaiShuffle(rng, arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = rng.int(0, i);
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

