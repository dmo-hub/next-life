export function chooseIsekai(isk, idx) {
  if (isk.step === 'world') {
    const w = isk.worldOffers[idx];
    if (!w) throw new Error('ตัวเลือกไม่ถูกต้อง');
    isekaiStart(isk, w);
    isk.step = 'skill';
    return;
  }
  if (isk.step === 'skill') {
    const s = isk.skillOffers[idx];
    if (!s) throw new Error('ตัวเลือกไม่ถูกต้อง');
    isk.skills.push(s);
    if (s === 'luck') isk.st.luk += 15;
    isekaiQueue(isk);
    isk.step = 'event';
    return;
  }
  if (isk.step !== 'event') throw new Error('การ์ดนี้ไม่มีตัวเลือก');
  const ev = isekaiById[isk.queue[isk.idx].id];
  const c = ev.choices[idx];
  if (!c) throw new Error('ตัวเลือกไม่ถูกต้อง');
  if (c.need && isk.st.gold < c.need.gold) throw new Error('ตัวเลือกนี้ล็อกอยู่');
  let ok = true, out = c;
  if (c.stat) {
    ok = isk.rng.next() * 100 < isekaiChance(isk, c);
    out = ok ? c.win : c.lose;
  }
  const deltas = isekaiApply(isk, out.fx);
  for (const f of [out.flag, out.flag2]) if (f) isk.flags[f] = true;
  let sys = null;
  if (out.skill) {
    const rest = Object.keys(ISEKAI_SKILLS).filter((k) => !isekaiHas(isk, k) && k !== 'luck');
    if (rest.length) {
      const s = isk.rng.pick(rest);
      isk.skills.push(s);
      sys = `ได้รับสกิลใหม่ · ${ISEKAI_SKILLS[s].name}`;
    }
  }
  if (isekaiHas(isk, 'regen') && isk.st.hp > 0) isk.st.hp = isekaiClamp(isk.st.hp + 6, 0, 100);
  if (isk.st.hp <= 0) {
    if (isekaiHas(isk, 'rbd') && !isk.rbdUsed) {
      isk.rbdUsed = true;
      isk.st.hp = 40;
      sys = 'เสียงนาฬิกาดังในหัว เวลาย้อนกลับ · ย้อนเวลาเมื่อตาย ใช้ไปแล้ว';
    } else isk.dead = true;
  }
  isk.log.push(`${ev.title} · ${c.t}${c.stat ? (ok ? ' (สำเร็จ)' : ' (พลาด)') : ''}`);
  isk.last = { title: ev.title, text: out.text, ok: c.stat ? ok : null, stat: c.stat ? ISEKAI_STAT[c.stat] : null, deltas, sys };
  isk.step = 'result';
}

